/**
 * Splits src/styles.css into a per-component CSS bundle.
 *
 * Everything is generated from src/styles.css; no CSS is hand-edited here:
 *   dist/styles.css              verbatim copy of src/styles.css (compat entry)
 *   dist/css/tokens.css          base layer: :root tokens, theme block and the
 *                                shared utilities components compose onto their
 *                                own elements (`ui-scroll-y`, ...)
 *   dist/css/components/<X>.css  every rule whose selector names that component's
 *                                stem, with @media/@supports wrappers rebuilt
 *                                around the rules that belong in the file
 *
 * A rule whose selector names several component stems is written to each of
 * those files; that duplication is expected and documented in README.md.
 *
 * The script re-parses what it wrote and exits non-zero unless every source
 * rule, selector, declaration block and @keyframes block is accounted for.
 */
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = resolve(root, 'src/styles.css');
const DIST = resolve(root, 'dist');
const DIST_CSS = resolve(DIST, 'css');
const COMPONENTS_DIR = resolve(DIST_CSS, 'components');

const BANNER =
  '/* Generated by scripts/build-css.mjs from src/styles.css. Do not edit: change ' +
  'src/styles.css and rebuild. */\n';

const TOKENS_HEADER = '/* Base layer: design tokens, theme tokens and shared utilities. */\n\n';


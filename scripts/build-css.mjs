/**
 * Classes that belong to the base layer rather than to one component: the theme
 * alias and the utilities components compose onto their own elements
 * (`ui-scroll-y` on the Modal panel, `ui-visually-hidden` on hidden labels,
 * `ui-section-stack` inside Card). Keeping them in tokens.css is what makes a
 * single component file usable on its own.
 */
const BASE_CLASSES = new Set([
  'ui-theme-light',
  'ui-scroll-y',
  'ui-visually-hidden',
  'ui-section-stack',
]);

const PREFIX_TO_FILE = new Map();
for (const [file, prefixes] of STEM_GROUPS) {
  for (const prefix of prefixes) {
    if (PREFIX_TO_FILE.has(prefix)) throw new Error(`prefix ${prefix} listed twice`);
    PREFIX_TO_FILE.set(prefix, file);
  }
}
const PREFIXES = [...PREFIX_TO_FILE.keys()].sort((a, b) => b.length - a.length);

/* -------------------------------------------------------------------------- */
/* Parser                                                                     */
/* -------------------------------------------------------------------------- */

function skipString(css, i) {
  const quote = css[i];
  i += 1;
  while (i < css.length) {
    if (css[i] === '\\') {
      i += 2;
      continue;
    }
    if (css[i] === quote) return i + 1;
    i += 1;
  }
  throw new Error('unterminated string in stylesheet');
}

function skipComment(css, i) {
  const end = css.indexOf('*/', i + 2);
  if (end < 0) throw new Error('unterminated comment in stylesheet');
  return end + 2;
}

function findBlockEnd(css, i) {
  let depth = 0;
  while (i < css.length) {
    const c = css[i];
    if (c === '"' || c === "'") {
      i = skipString(css, i);
      continue;
    }
    if (c === '/' && css[i + 1] === '*') {
      i = skipComment(css, i);
      continue;
    }
    if (c === '{') {
      depth += 1;
      i += 1;
      continue;
    }
    if (c === '}') {
      depth -= 1;
      i += 1;
      if (depth === 0) return i;
      continue;
    }
    i += 1;
  }
  throw new Error('unbalanced braces in stylesheet');
}

/**
 * Nodes:
 *   { type: 'rule',      leading, selector, raw }
 *   { type: 'group',     leading, prelude, children }  @media/@supports/@layer/@container
 *   { type: 'keyframes', leading, name, raw }
 *   { type: 'raw-block', leading, prelude, raw }       @font-face and friends
 *   { type: 'statement', leading, raw }                @charset/@import/...
 *   { type: 'comment',   raw }                         a comment with nothing after it
 */
function parseNodes(css) {
  const nodes = [];
  let i = 0;
  let leading = [];

  const flushOrphanComment = () => {
    if (leading.length) nodes.push({ type: 'comment', raw: leading.join('\n') });
    leading = [];
  };

  while (i < css.length) {
    const c = css[i];
    if (/\s/.test(c)) {
      i += 1;
      continue;
    }
    if (c === '/' && css[i + 1] === '*') {
      const end = skipComment(css, i);
      leading.push(css.slice(i, end));
      i = end;
      continue;
    }

    const start = i;
    let j = i;
    let paren = 0;
    let statement = false;
    while (j < css.length) {
      const d = css[j];
      if (d === '"' || d === "'") {
        j = skipString(css, j);
        continue;
      }
      if (d === '/' && css[j + 1] === '*') {
        j = skipComment(css, j);
        continue;
      }
      if (d === '(') {
        paren += 1;
        j += 1;
        continue;
      }
      if (d === ')') {
        paren -= 1;
        j += 1;
        continue;
      }
      if (paren === 0 && d === '{') break;
      if (paren === 0 && d === ';') {
        statement = true;
        j += 1;
        break;
      }
      j += 1;
    }
    if (j >= css.length) throw new Error(`unterminated prelude at offset ${start}`);

    if (statement) {
      nodes.push({ type: 'statement', leading, raw: css.slice(start, j).trim() });
      leading = [];
      i = j;
      continue;
    }

    const prelude = css.slice(start, j).trim();
    const end = findBlockEnd(css, j);
    const raw = css.slice(start, end);
    const inner = css.slice(j + 1, end - 1);

    if (prelude.startsWith('@')) {
      const name = prelude.split(/[\s{]/)[0].toLowerCase();
      if (name.endsWith('keyframes')) {
        nodes.push({ type: 'keyframes', leading, name: prelude.split(/\s+/)[1], raw });
      } else if (/^@(media|supports|layer|container|scope)$/.test(name)) {
        nodes.push({ type: 'group', leading, prelude, children: parseNodes(inner) });
      } else {
        nodes.push({ type: 'raw-block', leading, prelude, raw });
      }
    } else {
      nodes.push({ type: 'rule', leading, selector: prelude, raw });
    }
    leading = [];
    i = end;
  }
  flushOrphanComment();
  return nodes;
}

/* -------------------------------------------------------------------------- */
/* Classification                                                             */
/* -------------------------------------------------------------------------- */

function classesIn(selector) {
  return [...new Set([...selector.matchAll(/\.ui-[A-Za-z0-9_-]+/g)].map((m) => m[0].slice(1)))];
}

function stemOf(className) {
  const base = className.replace(/^ui-/, '').split('--')[0];
  for (const prefix of PREFIXES) {
    if (base === prefix || base.startsWith(`${prefix}-`)) return PREFIX_TO_FILE.get(prefix);
  }
  return null;
}

function animationNames(body) {
  const found = new Set();
  for (const match of body.matchAll(/animation(?:-name)?\s*:\s*([^;]+)/g)) {
    for (const name of match[1].matchAll(/ui-[A-Za-z0-9_-]+/g)) found.add(name[0]);
  }
  return found;
}

function flatten(nodes, out) {
  for (const node of nodes) {
    if (node.type === 'rule') out.push(node);
    else if (node.type === 'group') flatten(node.children, out);
  }
  return out;
}

/** Whitespace-insensitive form used by the self-check (media rules are re-indented). */
function norm(text) {
  return text.replace(/\s+/g, ' ').trim();
}

function indent(raw) {
  return raw
    .split('\n')
    .map((line) => (line.length ? `  ${line}` : line))
    .join('\n');
}

function joinChunks(chunks) {
  const parts = chunks.map((chunk) => [...(chunk.leading ?? []), chunk.raw].join('\n'));
  return parts.length ? `${parts.join('\n\n')}\n` : '';
}

/* -------------------------------------------------------------------------- */
/* Plan                                                                       */
/* -------------------------------------------------------------------------- */

const sourceText = await readFile(SOURCE, 'utf8');
const tree = parseNodes(sourceText);
const flat = flatten(tree, []);
const sourceRules = new Set(flat);

const problems = [];
const summarise = (items) =>
  `${items
    .slice(0, 3)
    .map((item) => item.replace(/\s+/g, ' '))
    .join(' | ')}` + (items.length > 3 ? ` | … ${items.length - 3} more` : '');
const unassigned = [];
const unmapped = new Set();
const baseRules = [];
const stemRules = new Map(STEM_GROUPS.map(([file]) => [file, []]));
const keyframes = new Map();

let assignedOccurrences = 0;
let duplicatedRules = 0;

for (const node of tree) {
  if (node.type === 'keyframes') keyframes.set(node.name, node);
  if (node.type === 'raw-block') {
    problems.push(`at-rule with no split rule: ${node.prelude}`);
  }
  if (node.type === 'statement') problems.push(`stylesheet-level statement: ${node.raw}`);
}

for (const rule of flat) {
  const classes = classesIn(rule.selector);
  const baseOnly = classes.every((className) => BASE_CLASSES.has(className));
  const stems = new Set();

  if (!baseOnly) {
    for (const className of classes) {
      if (BASE_CLASSES.has(className)) continue;
      const stem = stemOf(className);
      if (stem) stems.add(stem);
      else unmapped.add(className);
    }
  }

  if (baseOnly) {
    baseRules.push(rule);
    continue;
  }
  if (stems.size === 0) {
    unassigned.push(rule.selector);
    continue;
  }

  if (stems.size > 1) duplicatedRules += 1;
  assignedOccurrences += stems.size;
  for (const stem of stems) stemRules.get(stem).push(rule);
}

if (unmapped.size) {
  console.error(
    'No stem for these classes — extend STEM_GROUPS or BASE_CLASSES in ' +
      `scripts/build-css.mjs: ${[...unmapped].sort().join(', ')}`,
  );
  process.exit(1);
}

const componentRules = flat.length - baseRules.length - unassigned.length;

const keyframesOwners = new Map([...keyframes.keys()].map((name) => [name, new Set()]));
for (const [stem, rules] of stemRules) {
  for (const rule of rules) {
    for (const name of animationNames(rule.raw)) {
      if (!keyframesOwners.has(name)) {
        problems.push(`rule ${rule.selector} animates with unknown @keyframes ${name}`);
        continue;
      }
      keyframesOwners.get(name).add(stem);
    }
  }
}
const keyframesBase = [...keyframes.keys()].filter((name) => keyframesOwners.get(name).size === 0);

/* -------------------------------------------------------------------------- */
/* Emit                                                                       */
/* -------------------------------------------------------------------------- */

/** Body for a set of rules: wrappers and leading comments travel with them. */
function buildBody(rules, extraKeyframes) {
  const keep = new Set(rules);
  const chunks = [];
  for (const node of tree) {
    if (node.type === 'group') {
      const children = node.children.filter((child) => child.type === 'rule' && keep.has(child));
      if (!children.length) continue;
      const inner = children
        .map((child) => [...child.leading, indent(child.raw)].join('\n'))
        .join('\n\n');
      chunks.push({ leading: node.leading, raw: `${node.prelude} {\n${inner}\n}` });
    } else if (node.type === 'rule' && keep.has(node)) {
      chunks.push({ leading: node.leading, raw: node.raw });
    }
  }
  for (const node of extraKeyframes) chunks.push({ leading: node.leading, raw: node.raw });
  return joinChunks(chunks);
}

const baseBody = buildBody(
  baseRules,
  keyframesBase.map((name) => keyframes.get(name)),
);
const orphanComments = joinChunks(
  tree.filter((node) => node.type === 'comment').map((node) => ({ raw: node.raw })),
);

const tokensText = `${BANNER}${TOKENS_HEADER}${baseBody}${orphanComments ? `\n${orphanComments}` : ''}`;

await rm(COMPONENTS_DIR, { recursive: true, force: true });
await mkdir(COMPONENTS_DIR, { recursive: true });
await copyFile(SOURCE, resolve(DIST, 'styles.css'));
await writeFile(resolve(DIST_CSS, 'tokens.css'), tokensText);

const written = [];
for (const [stem, rules] of stemRules) {
  const ownKeyframes = [...keyframesOwners]
    .filter(([, owners]) => owners.has(stem))
    .map(([name]) => keyframes.get(name));
  const body = buildBody(rules, ownKeyframes);
  if (!body.trim()) continue;
  const file = resolve(COMPONENTS_DIR, `${stem}.css`);
  const header =
    `/* ${stem} — ${rules.length} rule(s) from src/styles.css. Rules shared with another ` +
    "component are repeated in that component's file. */\n\n";
  await writeFile(file, `${BANNER}${header}${body}`);
  written.push({ stem, file });
}

/* -------------------------------------------------------------------------- */
/* Self-check: re-parse the outputs                                           */
/* -------------------------------------------------------------------------- */

async function loadOutput(file) {
  const text = (await readFile(file, 'utf8')).replace(BANNER, '');
  return { text, tree: parseNodes(text) };
}

function countRules(nodes) {
  let total = 0;
  for (const node of nodes) {
    if (node.type === 'rule') total += 1;
    else if (node.type === 'group') total += countRules(node.children);
  }
  return total;
}

const tokensOut = await loadOutput(resolve(DIST_CSS, 'tokens.css'));
const componentOut = new Map();
for (const entry of written) componentOut.set(entry.stem, await loadOutput(entry.file));

const tokensRuleCount = countRules(tokensOut.tree);
const componentRuleCount = [...componentOut.values()].reduce(
  (sum, out) => sum + countRules(out.tree),
  0,
);

/* 1. accounting: nothing lost, duplicates made explicit */
if (tokensRuleCount !== baseRules.length) {
  problems.push(`tokens.css holds ${tokensRuleCount} rules, base bucket has ${baseRules.length}`);
}
if (componentRuleCount !== assignedOccurrences) {
  problems.push(
    `component files hold ${componentRuleCount} rules, expected ${assignedOccurrences}`,
  );
}
if (baseRules.length + componentRules !== sourceRules.size - unassigned.length) {
  problems.push(
    `accounting: ${baseRules.length} base + ${componentRules} component = ` +
      `${baseRules.length + componentRules}, source has ${sourceRules.size} rules`,
  );
}
if (unassigned.length) {
  problems.push(`${unassigned.length} rule(s) named no known stem: ${summarise(unassigned)}`);
}

/* 2. every source selector appears in at least one output */
const outputSelectors = new Set();
const collectSelectors = (nodes) => {
  for (const node of nodes) {
    if (node.type === 'rule') outputSelectors.add(norm(node.selector));
    else if (node.type === 'group') collectSelectors(node.children);
  }
};
collectSelectors(tokensOut.tree);
for (const out of componentOut.values()) collectSelectors(out.tree);

const missingSelectors = flat.filter((rule) => !outputSelectors.has(norm(rule.selector)));
if (missingSelectors.length) {
  problems.push(
    `${missingSelectors.length} selector(s) absent from every output: ` +
      summarise(missingSelectors.map((rule) => rule.selector)),
  );
}

/* 3. every declaration block is present verbatim in at least one output */
const allOutput = norm(
  [tokensOut.text, ...[...componentOut.values()].map((out) => out.text)].join('\n'),
);
const missingBodies = flat.filter(
  (rule) => !allOutput.includes(norm(rule.raw.slice(rule.raw.indexOf('{')))),
);
if (missingBodies.length) {
  problems.push(
    `${missingBodies.length} declaration block(s) absent from every output: ` +
      summarise(missingBodies.map((rule) => rule.selector)),
  );
}

/* 4. no foreign rules inside a component file */
for (const [stem, out] of componentOut) {
  const offenders = [];
  for (const rule of flatten(out.tree, [])) {
    const stems = new Set(
      classesIn(rule.selector)
        .filter((className) => !BASE_CLASSES.has(className))
        .map(stemOf)
        .filter(Boolean),
    );
    if (!stems.has(stem)) offenders.push(rule.selector);
  }
  if (offenders.length) problems.push(`${stem}.css holds foreign rules: ${summarise(offenders)}`);
}

/* 5. @keyframes coverage: a file that animates with a name carries its block */
for (const [name, owners] of keyframesOwners) {
  if (owners.size === 0 && !tokensOut.text.includes(`@keyframes ${name}`)) {
    problems.push(`@keyframes ${name} shipped nowhere`);
  }
  for (const owner of owners) {
    const out = componentOut.get(owner);
    if (!out) problems.push(`@keyframes ${name} belongs to ${owner}.css, which was not written`);
    else if (!out.text.includes(`@keyframes ${name}`)) {
      problems.push(`@keyframes ${name} missing from ${owner}.css`);
    }
  }
}

/* 6. dist/styles.css is a byte-for-byte copy of src/styles.css */
const copy = await readFile(resolve(DIST, 'styles.css'));
if (Buffer.compare(copy, Buffer.from(sourceText)) !== 0) {
  problems.push('dist/styles.css is not a byte-identical copy of src/styles.css');
}

if (problems.length) {
  console.error('\nstyles.css split FAILED its self-check:');
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

const size = (n) => `${n.toLocaleString('en-US')} B`;
console.log('src/styles.css split');
console.log(`  dist/styles.css       ${size(Buffer.byteLength(sourceText))} verbatim copy`);
console.log(`  dist/css/tokens.css   ${tokensRuleCount} base rules`);
console.log(`  dist/css/components/  ${written.length} files, ${componentRuleCount} rules written`);
console.log(
  `  rules accounted       ${sourceRules.size} source = ${baseRules.length} base + ` +
    `${componentRules} component (${assignedOccurrences} assignments, ` +
    `${duplicatedRules} rules shared across stems)`,
);
console.log(
  `  @keyframes            ${keyframes.size} blocks, ${keyframesBase.length} unreferenced` +
    `${keyframesBase.length ? ` (${keyframesBase.join(', ')} -> tokens.css)` : ''}`,
);
console.log(`  unassigned blocks     ${unassigned.length}`);
